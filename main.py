def load_events(path):
    with open(path, "r", encoding="utf-8-sig") as stream:
        data = json.load(stream)

    if isinstance(data, dict):
        data = data.get("events")

    if not isinstance(data, list):
        raise ValueError(
            "Неверная структура JSON-базы"
        )

    return [
        item for item in data
        if isinstance(item, dict)
    ]


def load_sent(path):
    if not Path(path).exists():
        return set()

    with open(path, "r", encoding="utf-8-sig") as stream:
        data = json.load(stream)

    if (
        not isinstance(data, list)
        or not all(isinstance(x, str) for x in data)
    ):
        raise ValueError(
            "sent.json повреждён"
        )

    return set(data)


def save_sent(path, markers):
    destination = Path(path)

    destination.parent.mkdir(
        parents=True,
        exist_ok=True
    )

    temporary = destination.with_name(
        destination.name + ".tmp"
    )

    with temporary.open("w", encoding="utf-8") as stream:
        json.dump(
            sorted(markers),
            stream,
            ensure_ascii=False,
            indent=2
        )

        stream.flush()
        os.fsync(stream.fileno())

    os.replace(
        temporary,
        destination
    )


def event_identity(item, today):
    stable = item.get("id")

    if stable is None or as_text(stable) == "":
        stable = [
            item.get(key, "")
            for key in (
                "artist",
                "group",
                "date",
                "event"
            )
        ]

        stable.append(event_kind(item))

    raw = json.dumps(
        stable,
        ensure_ascii=False,
        sort_keys=True,
        default=str
    )

    digest = hashlib.sha256(
        raw.encode("utf-8")
    ).hexdigest()[:24]

    return f"{today.isoformat()}_{digest}"


def original_event_identity(item, today):
    raw = json.dumps(
        item,
        ensure_ascii=False,
        sort_keys=True
    )

    digest = hashlib.sha256(
        raw.encode("utf-8")
    ).hexdigest()

    return f"{today.year}_{digest}"


