def event_kind(item):
    kind = as_text(
        item.get("type")
        or item.get("event_type")
        or item.get("kind")
    ).casefold()

    if kind in {
        "birth", "birthday", "рождение", "день рождения"
    }:
        return "birth"

    if kind in {
        "death", "memorial", "смерть", "память"
    }:
        return "death"

    event = as_text(item.get("event")).casefold()

    if re.search(
        r"\b(родился|родилась|день рождения)\b",
        event
    ):
        return "birth"

    if re.search(
        r"\b(умер|умерла|погиб|погибла|"
        r"скончался|скончалась|смерть|"
        r"уш[её]л из жизни|ушла из жизни)\b",
        event
    ):
        return "death"

    return "other"


def date_for_event(item):
    parsed = parse_date(
        item.get("date") or item.get("event_date")
    )

    if parsed is None:
        return None

    kind = event_kind(item)

    if kind == "birth":
        years = (
            item.get("birth_year"),
            item.get("year_of_birth")
        )
    elif kind == "death":
        years = (
            item.get("death_year"),
            item.get("year_of_death")
        )
    else:
        years = ()

    return with_year(
        parsed,
        *years,
        item.get("event_year"),
        item.get("year")
    )


def person_birth_date(item):
    parsed = parse_date(
        item.get("birth_date") or item.get("born_date")
    )

    if parsed is None and event_kind(item) == "birth":
        parsed = date_for_event(item)

    return with_year(
        parsed,
        item.get("birth_year"),
        item.get("year_of_birth")
    )


def person_death_date(item):
    parsed = parse_date(item.get("death_date"))

    if parsed is None and event_kind(item) == "death":
        parsed = date_for_event(item)

    return with_year(
        parsed,
        item.get("death_year"),
        item.get("year_of_death")
    )


