def person_info(item):
    artist = html(
        item.get("artist") or "Музыкант",
        170
    )

    lines = [f"👤 <b>{artist}</b>"]

    group = as_text(item.get("group"))
    role = as_text(item.get("role"))

    about = []

    if group:
        about.append(
            f"🎵 {html(group, 150)}"
        )

    if role:
        # Строго как в JSON:
        # "гитара", а не "гитарист".
        about.append(
            f"🎼 {html(role, 150)}"
        )

    if about:
        lines.append("  ·  ".join(about))

    return lines


def format_birth(item, today, people):
    lines = person_info(item)

    birthday, death = known_dates(item, people)

    if birthday:
        lines.append(
            f"📅 {birthday.display()}"
        )

    if (
        birthday is not None
        and birthday.year is not None
        and birthday.year <= today.year
    ):
        age = today.year - birthday.year

        if died_by(item, today, death):
            lines.append(
                f"🎂 <b>Сегодня исполнилось бы "
                f"{age} {years_word(age)}</b>"
            )
        else:
            lines.append(
                f"🎉 <b>Сегодня исполнилось "
                f"{age} {years_word(age)}</b>"
            )
    else:
        lines.append("🎂 Возраст: Секрет")

    if death and died_by(item, today, death):
        lines.append(
            f"🕯️ Дата ухода: {death.display()}"
        )

    return "\n".join(lines)


def format_death(item, today, people):
    lines = person_info(item)

    birthday, death = known_dates(item, people)

    if death:
        lines.append(
            f"📅 Дата ухода: {death.display()}"
        )

        if (
            death.year is not None
            and death.year <= today.year
        ):
            years = today.year - death.year

            lines.append(
                f"🕯️ <b>{years} {years_word(years)} "
                f"со дня ухода</b>"
            )
    else:
        lines.append("🕯️ Дата ухода: Секрет")

    age = age_at_death(
        birthday,
        death
    )

    if age is not None:
        lines.append(
            f"🌹 Возраст на момент смерти: "
            f"{age} {years_word(age)}"
        )
    else:
        lines.append(
            "🌹 Возраст на момент смерти: Секрет"
        )

    return "\n".join(lines)


