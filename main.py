def common_header(today, part=None, total=None):
    result = [
        "🎸 <b>РОК-КАЛЕНДАРЬ</b>",
        (
            f"📅 {today.day} "
            f"{RUS_MONTHS[today.month]} "
            f"{today.year} года"
        ),
        "🃏 Рок-сообщество"
    ]

    if (
        part is not None
        and total is not None
        and total > 1
    ):
        result.append(
            f"📄 Часть {part}/{total}"
        )

    return "\n".join(result)


def publication_text(
    title,
    cards,
    today,
    total_people,
    include_quote=False,
    part=1,
    total_parts=1
):
    lines = [
        common_header(today, part, total_parts),
        "",
        SEPARATOR,
        "",
        title,
        f"Музыкантов: {total_people}",
        ""
    ]

    for index, (_, content) in enumerate(cards):
        if index:
            lines.extend([
                "",
                "· · ·",
                ""
            ])

        lines.append(content)

    if include_quote:
        lines.extend([
            "",
            SEPARATOR,
            "",
            phrase_footer(today)
        ])

    return "\n".join(lines)


def sort_event(entry):
    _, item = entry

    dt = date_for_event(item)

    year = (
        dt.year
        if dt and dt.year is not None
        else 10000
    )

    artist = as_text(
        item.get("artist")
    ).casefold()

    return (
        year == 10000,
        year,
        artist
    )


def build_publications(events, today, people):
    sections = (
        ("death", format_death),
        ("birth", format_birth)
    )

    batches = []

    for kind, formatter in sections:
        rows = [
            (event_id, item)
            for event_id, item in events
            if event_kind(item) == kind
        ]

        if not rows:
            continue

        title = section_heading(
            kind,
            [item for _, item in rows]
        )

        rows.sort(key=sort_event)

        cards = [
            (
                event_id,
                formatter(item, today, people)
            )
            for event_id, item in rows
        ]

        groups = []
        current = []

        for card in cards:
            candidate = current + [card]

            test_message = publication_text(
                title,
                candidate,
                today,
                len(rows),
                include_quote=True
            )

            if (
                len(test_message) > MAX_MESSAGE_LENGTH - 80
                and current
            ):
                groups.append(current)
                current = []

            single_message = publication_text(
                title,
                [card],
                today,
                len(rows),
                include_quote=True
            )

            if len(single_message) > MAX_MESSAGE_LENGTH - 80:
                LOG.error(
                    "Слишком длинная запись: %s",
                    card[0]
                )
                continue

            current.append(card)

        if current:
            groups.append(current)

        for number, group in enumerate(groups, 1):
            batches.append(
                (
                    title,
                    len(rows),
                    group,
                    number,
                    len(groups)
                )
            )

    publications = []

    for index, batch in enumerate(batches):
        title, count, group, part, total_parts = batch

        content = publication_text(
            title,
            group,
            today,
            count,
            part=part,
            total_parts=total_parts,
            include_quote=(
                index == len(batches) - 1
            )
        )

        if len(content) > MAX_MESSAGE_LENGTH:
            raise ValueError(
                "Сообщение превышает лимит Telegram"
            )

        publications.append(
            Publication(
                event_ids=tuple(
                    event_id for event_id, _ in group
                ),
                text=content
            )
        )

    return publications


