def make_session():
    session = requests.Session()

    session.mount(
        "https://",
        HTTPAdapter(
            pool_connections=10,
            pool_maxsize=10
        )
    )

    return session


def send_telegram(session, token, channel_id, text):
    url = (
        f"https://api.telegram.org/bot{token}/sendMessage"
    )

    payload = {
        "chat_id": channel_id,
        "text": text,
        "parse_mode": "HTML",
        "disable_web_page_preview": True
    }

    for attempt in range(MAX_RETRIES):
        try:
            response = session.post(
                url,
                data=payload,
                timeout=20
            )

            if (
                response.ok
                and response.json().get("ok") is True
            ):
                return True

            if response.status_code == 429:
                try:
                    delay = int(
                        response.json()
                        .get("parameters", {})
                        .get("retry_after", 3)
                    )
                    delay = min(60, max(1, delay))
                except (ValueError, TypeError):
                    delay = 3

            elif response.status_code >= 500:
                delay = 2 ** attempt

            else:
                LOG.error(
                    "Telegram HTTP %s: %s",
                    response.status_code,
                    response.text[:250]
                )
                return False

        except (requests.RequestException, ValueError) as exc:
            LOG.warning(
                "Ошибка Telegram: %s",
                exc
            )

            delay = 2 ** attempt

        if attempt < MAX_RETRIES - 1:
            time.sleep(delay)

    return False


