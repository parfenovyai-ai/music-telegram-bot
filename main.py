def get_phrase(today: date | None = None, post_number: int = 0) -> str:
    """Одна рок-мысль на сообщение. Каждый день новая; 300-дневный цикл.

    Множитель 173 взаимно прост с 300: при одном посте в день
    все 300 мыслей будут использованы до первого повтора.
    Выбор устойчив к перезапускам и не затрагивает sent.json.
    """
    if today is None:
        today = datetime.now(MOSCOW_TZ).date()
    return ROCK_PHRASES[(today.toordinal() * 173 + post_number) % len(ROCK_PHRASES)]


def phrase_footer(today: date, post_number: int = 0) -> str:
    quote = html(get_phrase(today, post_number), 500)
    return f"🎸 <b>РОК-МЫСЛЬ ДНЯ</b>\n<i>«{quote}»</i>"


