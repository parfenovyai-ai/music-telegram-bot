def person_key(item):
    """
    Имя музыканта и набор групп.

    Порядок групп не влияет на результат.

    Например:
    Dead Kennedys/Red Hot Chili Peppers
    Red Hot Chili Peppers/Dead Kennedys

    Получают один и тот же ключ.
    """

    artist = " ".join(
        as_text(item.get("artist")).casefold().split()
    )

    groups = [
        " ".join(group.casefold().split())
        for group in as_text(item.get("group")).split("/")
    ]

    group_key = "/".join(
        sorted(group for group in groups if group)
    )

    if not artist:
        return None

    return artist, group_key


def consistent_date(dates):
    if not dates:
        return None

    day_month = {
        (d.day, d.month) for d in dates
    }

    if len(day_month) != 1:
        return None

    complete = {
        d for d in dates if d.year is not None
    }

    if len(complete) > 1:
        return None

    if complete:
        return next(iter(complete))

    return next(iter(dates))


def index_person_history(events):
    candidates = {}

    for item in events:
        key = person_key(item)
        kind = event_kind(item)
        dt = date_for_event(item)

        if key is None or kind not in (
            "birth", "death"
        ) or dt is None:
            continue

        records = candidates.setdefault(
            key,
            {"birth": set(), "death": set()}
        )

        records[kind].add(dt)

    return {
        key: PersonHistory(
            birth=consistent_date(values["birth"]),
            death=consistent_date(values["death"])
        )
        for key, values in candidates.items()
    }


def merged_date(direct, inferred):
    if direct is None:
        return inferred

    if inferred is None:
        return direct

    if (
        direct.day, direct.month
    ) != (
        inferred.day, inferred.month
    ):
        return None

    if (
        direct.year is not None
        and inferred.year is not None
        and direct.year != inferred.year
    ):
        return None

    if direct.year is not None:
        return direct

    return inferred


def known_dates(item, people):
    key = person_key(item)

    history = people.get(key)

    birth = merged_date(
        person_birth_date(item),
        history.birth if history else None
    )

    death = merged_date(
        person_death_date(item),
        history.death if history else None
    )

    return birth, death


