def check_events(
    db_path=DB_FILE,
    sent_path=SENT_FILE,
    today=None,
    dry_run=False
):
    if today is None:
        today = datetime.now(MOSCOW_TZ).date()

    events = load_events(db_path)

    people = index_person_history(events)

    sent = (
        set()
        if dry_run
        else load_sent(sent_path)
    )

    pending = []
    seen = set()

    for item in events:
        dt = date_for_event(item)

        if dt is None:
            LOG.warning(
                "Некорректная дата: %s",
                item.get("artist", "?")
            )
            continue

        if (dt.day, dt.month) != (today.day, today.month):
            continue

        if dt.year is not None and dt.year > today.year:
            continue

        kind = event_kind(item)

        if kind not in ("birth", "death"):
            continue

        marker = event_identity(item, today)

        old_marker = original_event_identity(
            item,
            today
        )

        if (
            marker in seen
            or marker in sent
            or old_marker in sent
        ):
            continue

        pending.append(
            (marker, item)
        )

        seen.add(marker)

    posts = build_publications(
        pending,
        today,
        people
    )

    LOG.info(
        "Дата %s | Событий: %d | Сообщений: %d",
        today.isoformat(),
        len(pending),
        len(posts)
    )

    if dry_run:
        if not posts:
            print("Для выбранной даты событий нет.")

        for number, post in enumerate(posts, 1):
            print("\n" + "=" * 50)
            print(f"ПРЕДПРОСМОТР {number}/{len(posts)}")
            print("=" * 50)
            print(post.text)

        print(
            "\nПредпросмотр завершён. "
            "Telegram и sent.json не изменены."
        )
        return 0

    if not posts:
        return 0

    token = as_text(
        os.getenv("BOT_TOKEN")
    )

    channel_id = as_text(
        os.getenv("CHANNEL_ID")
    )

    if not token or not channel_id:
        raise RuntimeError(
            "Не указаны BOT_TOKEN или CHANNEL_ID"
        )

    sent_count = 0
    session = make_session()

    try:
        for number, post in enumerate(posts, 1):
            success = send_telegram(
                session,
                token,
                channel_id,
                post.text
            )

            if success:
                sent.update(post.event_ids)

                save_sent(
                    sent_path,
                    sent
                )

                sent_count += 1

                LOG.info(
                    "Отправлено сообщение %d/%d",
                    number,
                    len(posts)
                )

            else:
                LOG.error(
                    "Не удалось отправить сообщение %d/%d",
                    number,
                    len(posts)
                )

            if number < len(posts):
                time.sleep(SEND_DELAY)

    finally:
        session.close()

    return sent_count


