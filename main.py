def years_word(n):
    if 11 <= n % 100 <= 14:
        return "лет"

    if n % 10 == 1:
        return "год"

    if n % 10 in (2, 3, 4):
        return "года"

    return "лет"


def age_at_death(born, died):
    if (
        born is None
        or died is None
        or born.year is None
        or died.year is None
    ):
        return None

    birth_day = date(
        born.year, born.month, born.day
    )

    death_day = date(
        died.year, died.month, died.day
    )

    if death_day < birth_day:
        return None

    age = died.year - born.year

    if (
        died.month, died.day
    ) < (
        born.month, born.day
    ):
        age -= 1

    return age


def died_by(item, today, death):
    if item.get("deceased") is True:
        return True

    if item.get("alive") is False:
        return True

    if death is not None:
        if death.year is None:
            return True

        return date(
            death.year,
            death.month,
            death.day
        ) <= today

    year = valid_year(
        item.get("death_year")
        or item.get("year_of_death")
    )

    return (
        year is not None
        and year <= today.year
    )


