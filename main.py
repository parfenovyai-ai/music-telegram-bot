def main():
    parser = argparse.ArgumentParser(
        description="Рок-сообщество — Telegram-бот"
    )

    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Предпросмотр без отправки"
    )

    parser.add_argument(
        "--date",
        help="Дата YYYY-MM-DD"
    )

    parser.add_argument(
        "--db",
        default=DB_FILE
    )

    parser.add_argument(
        "--sent",
        default=SENT_FILE
    )

    args = parser.parse_args()

    if args.date and not args.dry_run:
        parser.error(
            "--date допустима только с --dry-run"
        )

    try:
        selected_date = (
            date.fromisoformat(args.date)
            if args.date
            else None
        )

        check_events(
            db_path=args.db,
            sent_path=args.sent,
            today=selected_date,
            dry_run=args.dry_run
        )

    except (OSError, ValueError, RuntimeError) as exc:
        LOG.error(
            "Работа бота прервана: %s",
            exc
        )

        raise SystemExit(1) from exc


if __name__ == "__main__":
    main()
