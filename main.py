@dataclass(frozen=True)
class EventDate:
    day: int
    month: int
    year: int | None = None

    def display(self):
        result = f"{self.day:02d}.{self.month:02d}"
        return result + (
            f".{self.year}" if self.year is not None else ""
        )


@dataclass(frozen=True)
class PersonHistory:
    birth: EventDate | None = None
    death: EventDate | None = None


@dataclass(frozen=True)
class Publication:
    event_ids: tuple[str, ...]
    text: str


def parse_date(value):
    value = as_text(value)

    if not value:
        return None

    iso = re.fullmatch(
        r"(\d{4})-(\d{1,2})-(\d{1,2})",
        value
    )

    if iso:
        year, month, day = map(int, iso.groups())
    else:
        match = re.fullmatch(
            r"(\d{1,2})[-./](\d{1,2})(?:[-./](\d{4}))?",
            value
        )

        if not match:
            return None

        day = int(match.group(1))
        month = int(match.group(2))
        year = (
            int(match.group(3))
            if match.group(3)
            else None
        )

    try:
        date(year if year is not None else 2000, month, day)
    except ValueError:
        return None

    return EventDate(day, month, year)


def valid_year(value):
    if isinstance(value, bool):
        return None

    if not isinstance(value, (str, int)):
        return None

    raw = str(value).strip()

    if not re.fullmatch(r"\d{4}", raw):
        return None

    year = int(raw)

    return year if 1000 <= year <= 9999 else None


def with_year(parsed, *options):
    if parsed is None or parsed.year is not None:
        return parsed

    for option in options:
        year = valid_year(option)

        if year is None:
            continue

        try:
            date(year, parsed.month, parsed.day)
        except ValueError:
            continue

        return EventDate(parsed.day, parsed.month, year)

    return parsed


